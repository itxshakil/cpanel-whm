<?php

declare(strict_types=1);

namespace Itxshakil\CpanelWhm\Generator;

use RuntimeException;

/**
 * Writes the generated API classes, the function catalog and docs/coverage.md.
 */
final class Writer
{
    public const string HEADER = 'Generated by bin/generate from cPanel\'s OpenAPI spec. Do not edit; run composer generate.';

    /** @var list<string> */
    private array $written = [];

    public function __construct(private readonly string $root) {}

    /**
     * @param  list<Operation>  $whm
     * @param  list<Operation>  $uapi
     * @param  array<string, string>  $curated  WHM function => curated method
     * @return list<string> files written, relative to the root
     */
    public function write(array $whm, string $whmVersion, array $uapi, string $uapiVersion, array $curated): array
    {
        $this->written = [];

        $this->clean('src/Api/Whm');
        $this->clean('src/Api/Uapi');

        $whmGroups = $this->byGroup($whm);
        $uapiGroups = $this->byGroup($uapi);

        foreach ($whmGroups as $group => $operations) {
            $this->put("src/Api/Whm/{$group}.php", $this->whmClass($group, $operations, $whmVersion));
        }

        foreach ($uapiGroups as $group => $operations) {
            $this->put("src/Api/Uapi/{$group}.php", $this->uapiClass($group, $operations, $uapiVersion));
        }

        $this->put('src/Api/WhmApi.php', $this->entryClass('WhmApi', 'Whm', $whmGroups, $whmVersion));
        $this->put('src/Api/UapiApi.php', $this->entryClass('UapiApi', 'Uapi', $uapiGroups, $uapiVersion));
        $this->put('src/Support/FunctionCatalog.php', $this->catalog($whm, $whmVersion, $uapi, $uapiVersion));
        $this->put('docs/coverage.md', $this->coverage($whm, $whmVersion, $uapi, $uapiVersion, $curated));

        return $this->written;
    }

    /**
     * @param  list<Operation>  $operations
     * @return array<string, list<Operation>>
     */
    private function byGroup(array $operations): array
    {
        $groups = [];

        foreach ($operations as $operation) {
            if ($operation->generated()) {
                $groups[$operation->group][] = $operation;
            }
        }

        ksort($groups);

        return $groups;
    }

    /**
     * @param  list<Operation>  $operations
     */
    private function whmClass(string $group, array $operations, string $version): string
    {
        $methods = implode("\n", array_map(fn (Operation $o): string => $this->method($o, 'WhmResponse', true), $operations));
        $count = count($operations);

        return <<<PHP
            <?php

            declare(strict_types=1);

            // {$this->headerLine($version)}

            namespace Itxshakil\\CpanelWhm\\Api\\Whm;

            use Itxshakil\\CpanelWhm\\Api\\WhmGroup;
            use Itxshakil\\CpanelWhm\\Enums\\HttpMethod;
            use Itxshakil\\CpanelWhm\\Exceptions\\WhmException;
            use Itxshakil\\CpanelWhm\\WhmResponse;

            /**
             * WHM API 1: {$this->title($operations[0], $group)} ({$count} functions).
             *
             * Every method returns the checked WhmResponse; a failure throws a WhmException.
             */
            final class {$group} extends WhmGroup
            {
            {$methods}}

            PHP;
    }

    /**
     * @param  list<Operation>  $operations
     */
    private function uapiClass(string $group, array $operations, string $version): string
    {
        $methods = implode("\n", array_map(fn (Operation $o): string => $this->method($o, 'UapiResult', false), $operations));
        $module = Text::quote((string) $operations[0]->module);
        $name = (string) $operations[0]->module;
        $count = count($operations);

        return <<<PHP
            <?php

            declare(strict_types=1);

            // {$this->headerLine($version)}

            namespace Itxshakil\\CpanelWhm\\Api\\Uapi;

            use Itxshakil\\CpanelWhm\\Api\\UapiModule;
            use Itxshakil\\CpanelWhm\\Data\\UapiResult;
            use Itxshakil\\CpanelWhm\\Exceptions\\UapiCallFailed;
            use Itxshakil\\CpanelWhm\\Exceptions\\WhmException;

            /**
             * UAPI {$name} module ({$count} functions), run as one cPanel account through WHM.
             */
            final class {$group} extends UapiModule
            {
                public const string MODULE = {$module};

            {$methods}}

            PHP;
    }

    private function method(Operation $operation, string $returns, bool $whm): string
    {
        $doc = ['/**', ' * '.rtrim($operation->summary, '.').'.'];

        if ($operation->description !== '' && $operation->description !== $operation->summary) {
            $doc[] = ' *';

            foreach (Text::wrap($operation->description) as $line) {
                $doc[] = ' * '.$line;
            }
        }

        $doc[] = ' *';

        $parameters = $operation->orderedParameters();

        foreach ($parameters as $parameter) {
            $description = $parameter->description !== '' ? '  '.$parameter->description : '';
            $doc[] = " * @param  {$parameter->docType()}  \${$parameter->variable}{$description}";
        }

        $doc[] = ' * @param  array<string, mixed>  $extra  Further parameters, sent as given.';
        $doc[] = ' *';

        if ($whm) {
            $doc[] = ' * @throws WhmException';
        } else {
            $doc[] = ' * @throws UapiCallFailed';
            $doc[] = ' * @throws WhmException';
        }

        if ($operation->deprecated) {
            $doc[] = ' *';
            $doc[] = ' * @deprecated cPanel has deprecated this function.';
        }

        $doc[] = ' *';
        $doc[] = ' * @see '.$operation->docsUrl;
        $doc[] = ' */';

        $signature = array_map(static fn (Parameter $p): string => '        '.$p->signature().',', $parameters);
        $signature[] = '        array $extra = [],';

        $params = array_map(static fn (Parameter $p): string => '            '.Text::quote($p->name).' => $'.$p->variable.',', $parameters);
        $paramsCode = $params === [] ? '[]' : "[\n".implode("\n", $params)."\n        ]";

        $function = Text::quote($operation->function);
        $call = $whm && ! $operation->readOnly
            ? "\$this->invoke({$function}, {$paramsCode}, \$extra, HttpMethod::Post)"
            : "\$this->invoke({$function}, {$paramsCode}, \$extra)";

        $lines = array_map(static fn (string $line): string => '    '.$line, $doc);
        $lines[] = "    public function {$operation->method}(";
        $lines = [...$lines, ...$signature];
        $lines[] = "    ): {$returns} {";
        $lines[] = "        return {$call};";
        $lines[] = '    }';

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<string, list<Operation>>  $groups
     */
    private function entryClass(string $class, string $namespace, array $groups, string $version): string
    {
        $uses = [];
        $accessors = [];
        $properties = [];

        foreach ($groups as $group => $operations) {
            $uses[] = "use Itxshakil\\CpanelWhm\\Api\\{$namespace}\\{$group};";
            $accessor = lcfirst($group);
            $title = $namespace === 'Whm' ? $this->title($operations[0], $group) : 'UAPI '.$operations[0]->module;
            $properties[] = "    private ?{$group} \${$accessor} = null;";
            $accessors[] = <<<PHP
                    /**
                     * {$title}: {$this->countLabel(count($operations))}.
                     */
                    public function {$accessor}(): {$group}
                    {
                        return \$this->{$accessor} ??= new {$group}(\$this->target);
                    }

                PHP;
        }

        sort($uses);
        $useBlock = implode("\n", $uses);
        $propertyBlock = implode("\n\n", $properties);
        $accessorBlock = implode("\n", $accessors);

        if ($namespace === 'Whm') {
            $targetUse = 'use Itxshakil\\CpanelWhm\\Contracts\\WhmClient;';
            $target = 'WhmClient';
            $intro = "Every documented WHM API 1 function as a typed method, grouped the way cPanel's\n * documentation groups them: Whm::api()->dns()->parseDnsZone(zone: 'example.com').";
        } else {
            $targetUse = 'use Itxshakil\\CpanelWhm\\Modules\\CpanelUser;';
            $target = 'CpanelUser';
            $intro = "Every documented UAPI function as a typed method, by module, run as one account:\n * Whm::asUser('acme')->api()->email()->listPops().";
        }

        return <<<PHP
            <?php

            declare(strict_types=1);

            // {$this->headerLine($version)}

            namespace Itxshakil\\CpanelWhm\\Api;

            {$targetUse}
            {$useBlock}

            /**
             * {$intro}
             */
            final class {$class}
            {
            {$propertyBlock}

                public function __construct(private readonly {$target} \$target) {}

            {$accessorBlock}}

            PHP;
    }

    /**
     * @param  list<Operation>  $whm
     * @param  list<Operation>  $uapi
     */
    private function catalog(array $whm, string $whmVersion, array $uapi, string $uapiVersion): string
    {
        $entries = static function (array $operations, bool $isWhm): string {
            $lines = [];

            /** @var Operation $operation */
            foreach ($operations as $operation) {
                $lines[] = sprintf(
                    '        %s => [%s, %s, %s, %s, %s],',
                    Text::quote($operation->key()),
                    $operation->generated() ? Text::quote(lcfirst($operation->group).'()->'.$operation->method.'()') : 'null',
                    Text::quote(rtrim($operation->summary, '.')),
                    $operation->readOnly ? 'true' : 'false',
                    $operation->deprecated ? 'true' : 'false',
                    $isWhm && ! $operation->readOnly ? "'POST'" : "'GET'",
                );
            }

            usort($lines, strcmp(...));

            return implode("\n", $lines);
        };

        $whmEntries = $entries($whm, true);
        $uapiEntries = $entries($uapi, false);
        $whmVersion = Text::quote($whmVersion);
        $uapiVersion = Text::quote($uapiVersion);

        return <<<PHP
            <?php

            declare(strict_types=1);

            // {$this->headerLine('')}

            namespace Itxshakil\\CpanelWhm\\Support;

            /**
             * Every function in cPanel's OpenAPI documents, with where it lives in this
             * package. Used by whm:functions, read-only retries and caching.
             *
             * Each entry: [method or null, summary, read-only, deprecated, HTTP method].
             */
            final class FunctionCatalog
            {
                public const string WHM_SPEC_VERSION = {$whmVersion};

                public const string UAPI_SPEC_VERSION = {$uapiVersion};

                /**
                 * @var array<string, array{0: string|null, 1: string, 2: bool, 3: bool, 4: string}>
                 */
                public const array WHM = [
            {$whmEntries}
                ];

                /**
                 * Keyed "Module::function".
                 *
                 * @var array<string, array{0: string|null, 1: string, 2: bool, 3: bool, 4: string}>
                 */
                public const array UAPI = [
            {$uapiEntries}
                ];

                public static function isReadOnly(string \$function): bool
                {
                    return self::WHM[\$function][2] ?? false;
                }

                public static function has(string \$function): bool
                {
                    return isset(self::WHM[\$function]);
                }

                /**
                 * @return array{method: string|null, summary: string, readOnly: bool, deprecated: bool, httpMethod: string}|null
                 */
                public static function whm(string \$function): ?array
                {
                    return isset(self::WHM[\$function]) ? self::describe(self::WHM[\$function]) : null;
                }

                /**
                 * @return array{method: string|null, summary: string, readOnly: bool, deprecated: bool, httpMethod: string}|null
                 */
                public static function uapi(string \$module, string \$function): ?array
                {
                    \$key = \$module.'::'.\$function;

                    return isset(self::UAPI[\$key]) ? self::describe(self::UAPI[\$key]) : null;
                }

                /**
                 * @param  array{0: string|null, 1: string, 2: bool, 3: bool, 4: string}  \$entry
                 * @return array{method: string|null, summary: string, readOnly: bool, deprecated: bool, httpMethod: string}
                 */
                private static function describe(array \$entry): array
                {
                    return ['method' => \$entry[0], 'summary' => \$entry[1], 'readOnly' => \$entry[2], 'deprecated' => \$entry[3], 'httpMethod' => \$entry[4]];
                }
            }

            PHP;
    }

    /**
     * @param  list<Operation>  $whm
     * @param  list<Operation>  $uapi
     * @param  array<string, string>  $curated
     */
    private function coverage(array $whm, string $whmVersion, array $uapi, string $uapiVersion, array $curated): string
    {
        $count = $this->countGenerated(...);
        $percent = static fn (int $part, int $total): string => $total === 0 ? '0' : number_format($part / $total * 100, 1);

        $whmTotal = count($whm);
        $whmGenerated = $count($whm);
        $uapiTotal = count($uapi);
        $uapiGenerated = $count($uapi);
        $whmCurated = count(array_filter($whm, static fn (Operation $o): bool => isset($curated[$o->function])));

        $lines = [
            '# API coverage',
            '',
            '<!-- '.self::HEADER.' -->',
            '',
            "Built from cPanel's OpenAPI documents: WHM API 1 spec {$whmVersion}, UAPI spec {$uapiVersion}.",
            '',
            '| API | Functions in the spec | Typed method | Coverage | Hand-written, typed results |',
            '| --- | ---: | ---: | ---: | ---: |',
            "| WHM API 1 | {$whmTotal} | {$whmGenerated} | {$percent($whmGenerated, $whmTotal)}% | {$whmCurated} |",
            "| UAPI (through WHM) | {$uapiTotal} | {$uapiGenerated} | {$percent($uapiGenerated, $uapiTotal)}% | |",
            '',
            'Every function, typed or not, can also be called by name: `Whm::call()` for WHM API 1 and `Whm::asUser($user)->uapi()` for UAPI.',
            '',
            '## Functions without a typed method',
            '',
            'These take a JSON body or a file upload, which WHM\'s form API cannot carry. Use `Whm::call()` with the parameters the documentation lists, where the function accepts them as form fields.',
            '',
            '| Function | Why |',
            '| --- | --- |',
        ];

        foreach ([...$whm, ...$uapi] as $operation) {
            if (! $operation->generated()) {
                $lines[] = "| `{$operation->key()}` | {$operation->skipReason} |";
            }
        }

        $lines[] = '';
        $lines[] = '## WHM API 1 by group';
        $lines[] = '';
        $lines[] = '| Group | Accessor | Functions |';
        $lines[] = '| --- | --- | ---: |';

        foreach ($this->byGroup($whm) as $group => $operations) {
            $lines[] = '| '.$this->title($operations[0], $group).' | `Whm::api()->'.lcfirst($group).'()` | '.count($operations).' |';
        }

        $lines[] = '';
        $lines[] = '## UAPI by module';
        $lines[] = '';
        $lines[] = '| Module | Accessor | Functions |';
        $lines[] = '| --- | --- | ---: |';

        foreach ($this->byGroup($uapi) as $group => $operations) {
            $lines[] = '| '.$operations[0]->module.' | `Whm::asUser($user)->api()->'.lcfirst($group).'()` | '.count($operations).' |';
        }

        return implode("\n", $lines)."\n";
    }

    private function title(Operation $operation, string $group): string
    {
        return $operation->title !== '' ? $operation->title : $group;
    }

    /**
     * @param  list<Operation>  $operations
     */
    private function countGenerated(array $operations): int
    {
        return count(array_filter($operations, static fn (Operation $o): bool => $o->generated()));
    }

    private function countLabel(int $count): string
    {
        return $count === 1 ? '1 function' : "{$count} functions";
    }

    private function headerLine(string $version): string
    {
        return $version === '' ? self::HEADER : self::HEADER.' Spec '.$version.'.';
    }

    private function put(string $relative, string $contents): void
    {
        $path = $this->root.'/'.$relative;
        $directory = dirname($path);

        if (! is_dir($directory) && ! mkdir($directory, 0o755, true) && ! is_dir($directory)) {
            throw new RuntimeException("Cannot create {$directory}.");
        }

        file_put_contents($path, $contents);
        $this->written[] = $relative;
    }

    /**
     * Remove previously generated files so a function cPanel drops disappears too.
     */
    private function clean(string $relative): void
    {
        foreach (glob($this->root.'/'.$relative.'/*.php') ?: [] as $file) {
            $contents = (string) file_get_contents($file);

            if (str_contains($contents, self::HEADER)) {
                unlink($file);
            }
        }
    }
}
